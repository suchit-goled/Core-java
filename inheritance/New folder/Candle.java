class Candle {
    String brand;
    String smell;
    double lenght;
    double price;
    String thread;
	
	Candle(String brand, String smell, double lenght, double price, String thread){
		
		this.brand=brand;
		this.smell=smell;
		this.lenght=lenght;
		this.price=price;
		this.thread=thread;
	}
}